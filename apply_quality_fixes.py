def apply(cur, conn, label, mapping, update_sql):
    applied = 0
    for row_id, arabic_text in mapping.items():
        cur.execute(update_sql, (arabic_text, row_id))
        applied += 1
    conn.commit()
    print(f"  {applied}/{len(mapping)} {label} applied.")


def main():
    print("Connecting to database...", flush=True)
    conn = pymysql.connect(
        host=DB_HOST, user=DB_USER, password=DB_PASSWORD, database=DB_NAME,
        charset="utf8mb4", connect_timeout=15,
    )
    conn.autocommit(False)
    print("Connected.\n", flush=True)

    try:
        with conn.cursor() as cur:
            apply(cur, conn, "book name(s)", BOOK_NAMES,
                  "UPDATE book_translations SET name = %s WHERE id = %s")
            apply(cur, conn, "page heading(s)", PAGE_HEADINGS,
                  "UPDATE book_page_translations SET heading = %s WHERE id = %s")
        print("\nDone.")
    finally:
        conn.close()


if __name__ == "__main__":
    main()